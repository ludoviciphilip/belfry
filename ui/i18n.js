let LANG = "en";

function pickLang(pref) {
  if (pref && pref !== "auto") return pref;
  const nav = (navigator.languages || [navigator.language || "en"]).join(",").toLowerCase();
  return /(^|,)pt/.test(nav) ? "pt" : "en";
}

function t(key, vars = {}) {
  let s = (STRINGS[LANG] && STRINGS[LANG][key]) || STRINGS.en[key] || key;
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

function tErr(msg) {
  if (LANG !== "pt") return msg;
  for (const [re, pt] of ERRORS_PT) if (re.test(msg)) return msg.replace(re, pt);
  return msg;
}

function applyI18n(root = document) {
  document.documentElement.lang = LANG === "pt" ? "pt-BR" : "en";
  root.querySelectorAll("[data-i18n]").forEach((el) => (el.textContent = t(el.dataset.i18n)));
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => (el.placeholder = t(el.dataset.i18nPlaceholder)));
  root.querySelectorAll("[data-i18n-title]").forEach((el) => (el.title = t(el.dataset.i18nTitle)));
}
